import { test, expect } from './game-test.mjs';
import { FlightState } from '../flight-missions.mjs';
import { LUNAR_TIMING } from '../lunar-trajectory.mjs';
import { checkpoint } from './flight-fixtures.mjs';

test('short Apollo extraction renders the nearby Earth without clipping its surface', async ({ page }) => {
  test.setTimeout(180000);
  const flight = new FlightState('apollo_11');
  flight.preflight = flight.countdown = 0;
  for (let i = 0; i < 500 && flight.kind !== 'moonTransfer' && !flight.failed; i++) flight.update(60, {}, 500, () => false);
  expect(flight.kind).toBe('moonTransfer');
  const timing = LUNAR_TIMING.apollo_11;
  const extraction = timing.tliBurn + timing.extractionDelay;
  while (flight.time < timing.tliBurn) flight.update(1, {}, 1);
  flight.advanceCoast(extraction - flight.time);
  flight.flightLength = 'short';
  flight.paused = true;
  const errors = [];
  page.on('pageerror', error => errors.push(error.message));
  await page.addInitScript(saved => localStorage.setItem('jugre.flight-save.v1', JSON.stringify(saved)), checkpoint(flight));
  await page.goto(process.env.JUGRE_TEST_GAME_URL || '/index.html');
  await expect(page.locator('#loading')).toBeHidden({ timeout: 90000 });
  await page.locator('[data-view=launch]').click();
  await page.locator('#launch-rocket').selectOption('apollo_11');
  await expect(page.locator('#flight-start')).toBeEnabled();
  await page.locator('#flight-start').click();
  await expect(page.locator('#broadcast-hud')).toBeVisible({ timeout: 90000 });
  await page.locator('#flight-load').click();
  await expect(page.locator('#flight-event')).toContainText(/восстановлены|Разворот Columbia/, { timeout: 90000 });
  await expect(page.locator('#flight-pause')).toHaveAttribute('aria-pressed', 'true');
  await page.locator('#flight-diagnostics').evaluate(element => { element.open = true; });
  await expect.poll(() => page.locator('.physics-values').getAttribute('data-snapshot')).toBeTruthy();
  await expect.poll(async () => {
    const data = await page.locator('.physics-values').evaluate(element => JSON.parse(element.dataset.snapshot));
    return data.rendering.maneuver?.durationS;
  }).toBe(1260);
  const checkSurface = async () => {
    const data = await page.locator('.physics-values').evaluate(element => JSON.parse(element.dataset.snapshot));
    const { near, position, earthPosition } = data.rendering.spaceCamera;
    const distance = Math.hypot(...position.map((value, i) => value - earthPosition[i])) - 63.71;
    expect(distance).toBeGreaterThan(0);
    expect(near).toBeLessThan(distance * .2);
    expect(near).toBeLessThan(Math.abs(distance - .08) * .2);
    expect(data.rendering.earthBackdropBlend).toBe(0);
  };
  await checkSurface();
  await page.locator('#flight-diagnostics').evaluate(element => { element.open = false; });
  await page.screenshot({ path: 'test-results/apollo-short-earth-surface.png' });
  const viewport = await page.locator('#viewport').boundingBox();
  await page.mouse.move(viewport.x + viewport.width * .6, viewport.y + viewport.height * .4);
  await page.mouse.down();
  await page.mouse.move(viewport.x + viewport.width * .45, viewport.y + viewport.height * .55, { steps: 12 });
  await page.mouse.up();
  await page.locator('#flight-diagnostics').evaluate(element => { element.open = true; });
  await expect.poll(async () => {
    const data = await page.locator('.physics-values').evaluate(element => JSON.parse(element.dataset.snapshot));
    return data.rendering.spaceCamera.near;
  }).toBeLessThan(.1);
  await checkSurface();
  await page.locator('#flight-diagnostics').evaluate(element => { element.open = false; });
  await page.screenshot({ path: 'test-results/apollo-short-earth-camera-rotated.png' });
  await expect(page.locator('#flight-skip-maneuver')).toBeVisible();
  await page.locator('#flight-skip-maneuver').click();
  await expect(page.locator('#flight-skip-maneuver')).toBeVisible();
  await expect(page.locator('#flight-save')).toBeEnabled();
  await expect(page.locator('#flight-pause')).toHaveAttribute('aria-pressed', 'true');
  await page.locator('#flight-save').click();
  const saved = await page.evaluate(() => JSON.parse(localStorage.getItem('jugre.flight-save.v1')));
  expect(saved.state.reported).toContain('apolloTransposition');
  expect(saved.state.timeline.events.find(event => event.id === 'lm-extraction').status).toBe('COMPLETE');
  expect(saved.state.values.totalTime - flight.totalTime).toBeCloseTo(1260, 5);
  expect(saved.state.values.paused).toBe(true);
  expect(saved.state.values.actualRate).toBe(1);
  expect(FlightState.fromSave(saved.state).time).toBe(saved.state.values.time);
  await page.locator('#flight-diagnostics').evaluate(element => { element.open = true; });
  await expect.poll(async () => {
    const data = await page.locator('.physics-values').evaluate(element => JSON.parse(element.dataset.snapshot));
    return data.rendering.rigid.assemblyCaptured;
  }).toBe(true);
  await page.locator('#flight-diagnostics').evaluate(element => { element.open = false; });
  await page.locator('#flight-load').click();
  await expect(page.locator('#flight-event')).toContainText(/восстановлены|restored/i);
  await expect(page.locator('#flight-skip-maneuver')).toBeVisible();
  await page.screenshot({ path: 'test-results/apollo-maneuver-skipped.png' });
  expect(errors).toEqual([]);
});
