import { test, expect } from './game-test.mjs';
import { coastFixture, checkpoint } from './flight-fixtures.mjs';
import { FlightState } from '../flight-missions.mjs';

test('short flight travels at ×1 with normal camera controls and a faster mission clock', async ({ page }) => {
  test.setTimeout(180000);
  const flight = coastFixture('mars');
  flight.flightLength = 'short';
  flight.paused = true;
  const errors = [];
  page.on('pageerror', error => errors.push(error.message));
  await page.addInitScript(saved => localStorage.setItem('jugre.flight-save.v1', JSON.stringify(saved)), checkpoint(flight));
  await page.goto('/index.html');
  await expect(page.locator('#loading')).toBeHidden({ timeout: 90000 });
  await page.locator('[data-view=launch]').click();
  await page.locator('#design-resume').click();
  await expect(page.locator('#flight-event')).toContainText(/восстановлены|restored/i, { timeout: 90000 });
  await expect(page.locator('#flight-wrapit')).toHaveCount(0);
  await expect(page.locator('#flight-warp')).toHaveValue('1');
  await expect(page.locator('#flight-warp')).toBeDisabled();
  await expect(page.locator('#flight-altitude-label')).toContainText('short route');
  await page.locator('#flight-pause').click();
  await expect(page.locator('#flight-status')).toHaveText('Short flight · accelerated transfer');
  await page.locator('#viewport').click({ position: { x: 150, y: 150 } });
  await page.locator('#flight-pause').click();
  await page.locator('#flight-save').click();
  await page.screenshot({ path: 'test-results/short-flight-compact-space.png' });
  const saved = await page.evaluate(() => JSON.parse(localStorage.getItem('jugre.flight-save.v1')).state);
  expect(saved.values.actualRate).toBe(1);
  expect(saved.values.totalTime).toBeGreaterThan(flight.totalTime + 1000);
  expect(saved.values.gameplaySeconds).toBeLessThan(10);
  await page.locator('#flight-load').click();
  await expect(page.locator('#flight-event')).toContainText(/восстановлены|restored/i);
  await expect(page.locator('#flight-pause')).toHaveAttribute('aria-pressed', 'true');
  await page.locator('#flight-pause').click();
  await expect(page.locator('#design-flight-summary')).toHaveText('Objectives complete', { timeout: 45000 });
  await page.locator('#flight-save').click();
  const arrived = await page.evaluate(() => JSON.parse(localStorage.getItem('jugre.flight-save.v1')).state);
  expect(arrived.values.complete).toBe(true);
  expect(arrived.values.actualRate).toBe(1);
  await page.screenshot({ path: 'test-results/short-flight-arrival.png' });
  expect(errors).toEqual([]);
});

test('Mars 2020 holds its attitude during compressed cruise after Earth departure', async ({ page }) => {
  test.setTimeout(150000);
  const flight = new FlightState('mars_2020', 'command', { flightLength: 'short' });
  flight.preflight = flight.countdown = 0;
  for (let i = 0; i < 2000 && flight.kind !== 'marsTransfer' && !flight.failed; i++) flight.update(2, {}, 20, () => false);
  expect(flight.kind).toBe('marsTransfer');
  flight.paused = true;
  const errors = [];
  page.on('pageerror', error => errors.push(error.message));
  await page.goto('/index.html');
  await expect(page.locator('#loading')).toBeHidden({ timeout: 90000 });
  await page.locator('[data-view=launch]').click();
  await page.locator('#launch-rocket').selectOption('mars_2020');
  await page.locator('#flight-start').click();
  await expect(page.locator('#broadcast-hud')).toBeVisible({ timeout: 90000 });
  await page.evaluate(saved => localStorage.setItem('jugre.flight-save.v1', JSON.stringify(saved)), checkpoint(flight));
  await page.locator('#flight-load').click();
  await expect(page.locator('#flight-event')).toContainText(/восстановлены|restored/i);
  await page.locator('#flight-diagnostics').evaluate(element => { element.open = true; });
  const reader = page.locator('.physics-values');
  await expect(reader).toHaveAttribute('data-snapshot', /marsTransfer/);
  const read = async () => JSON.parse(await reader.getAttribute('data-snapshot')).rendering;
  const before = await read();
  await page.locator('#flight-pause').click();
  await expect.poll(async () => (await read()).missionTimeS).toBeGreaterThan(before.missionTimeS + 250000);
  await page.locator('#flight-pause').click();
  const after = await read();
  expect(after.phase).toBe('marsTransfer');
  expect(Math.hypot(...after.bodyDirectionECEF.map((v, i) => v - before.bodyDirectionECEF[i]))).toBeLessThan(.03);
  expect(after.cameraTargetErrorM).toBeLessThan(1);
  expect(errors).toEqual([]);
});
